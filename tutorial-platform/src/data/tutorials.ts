const tutorialsByTrack = tutorials.reduce(
  (accumulator, tutorial) => {
    const trackList = accumulator[tutorial.track] ?? [];
    trackList.push(tutorial);
    accumulator[tutorial.track] = trackList;
    return accumulator;
  },
  {
    java: [] as TutorialMeta[],
    nextjs: [] as TutorialMeta[],
    nodejs: [] as TutorialMeta[],
    python: [] as TutorialMeta[],
    react: [] as TutorialMeta[],
  },
);

const tutorialByTrackAndSlug = tutorials.reduce(
  (accumulator, tutorial) => {
    accumulator.set(`${tutorial.track}::${tutorial.slug}`, tutorial);
    return accumulator;
  },
  new Map<string, TutorialMeta>(),
);

export function getTutorialsByTrack(track: TutorialMeta["track"]) {
  return tutorialsByTrack[track];
}

export function getTutorialBySlug(track: TutorialMeta["track"], slug: string) {
  return tutorialByTrackAndSlug.get(`${track}::${slug}`);
}
