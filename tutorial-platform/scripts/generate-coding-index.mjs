import { promises as fs } from "node:fs";
import path from "node:path";

const rootDir = process.cwd();
const codingRoot = path.join(rootDir, "public", "coding");
const outputFile = path.join(rootDir, "src", "data", "codingLessons.ts");
const dayFilePattern = /^day-(\d{3})-.+\.md$/i;

function toPosixPath(input) {
  return input.replaceAll("\\", "/");
}

function trackKeyFromFolder(folderName) {
  return folderName.toLowerCase().replace(/[^a-z0-9]/g, "");
}

async function extractTitle(filePath, fallbackSlug) {
  const content = await fs.readFile(filePath, "utf8");
  const headingMatch = content.match(/^#\s*Day\s*\d+\s*[—-]\s*(.+)$/m);

  if (headingMatch?.[1]) {
    return headingMatch[1].trim();
  }

  return fallbackSlug
    .replace(/^day-\d{3}-/, "")
    .split("-")
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
}

async function fileExists(filePath) {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function buildIndex() {
  const languageFolders = await fs.readdir(codingRoot, { withFileTypes: true });
  const lessons = [];

  for (const folder of languageFolders) {
    if (!folder.isDirectory()) {
      continue;
    }

    const track = trackKeyFromFolder(folder.name);
    const folderPath = path.join(codingRoot, folder.name);
    const files = await fs.readdir(folderPath, { withFileTypes: true });

    for (const file of files) {
      if (!file.isFile() || !dayFilePattern.test(file.name)) {
        continue;
      }

      const match = file.name.match(dayFilePattern);
      const dayNumber = Number(match[1]);
      const slug = file.name.replace(/\.md$/i, "");
      const filePath = path.join(folderPath, file.name);
      const title = await extractTitle(filePath, slug);
      const solutionFilePath = path.join(folderPath, "solutions", file.name);
      const hasSolution = await fileExists(solutionFilePath);

      lessons.push({
        track,
        slug,
        dayLabel: `Day ${dayNumber}`,
        title,
        order: dayNumber,
        fileName: file.name,
        contentPath: toPosixPath(path.join("coding", folder.name, file.name)),
        hasSolution,
        solutionPath: hasSolution
          ? toPosixPath(
              path.join("coding", folder.name, "solutions", file.name),
            )
          : null,
      });
    }
  }

  lessons.sort((a, b) => {
    if (a.track !== b.track) {
      return a.track.localeCompare(b.track);
    }
    return a.order - b.order;
  });

  const header = `// AUTO-GENERATED by scripts/generate-coding-index.mjs - do not edit by hand.\nimport type { CodingTrackKey } from "./codingTracks";\n\nexport type CodingLessonMeta = {\n  track: CodingTrackKey;\n  slug: string;\n  dayLabel: string;\n  title: string;\n  order: number;\n  fileName: string;\n  contentPath: string;\n  hasSolution: boolean;\n  solutionPath: string | null;\n};\n\nexport const codingLessons: CodingLessonMeta[] = ${JSON.stringify(lessons, null, 2)};\n\nexport function getCodingLessonsByTrack(track: CodingTrackKey) {\n  return codingLessons\n    .filter((lesson) => lesson.track === track)\n    .sort((a, b) => a.order - b.order);\n}\n\nexport function getCodingLessonBySlug(track: CodingTrackKey, slug: string) {\n  return codingLessons.find((lesson) => lesson.track === track && lesson.slug === slug);\n}\n\nexport function getAvailableCodingTracks(): CodingTrackKey[] {\n  return Array.from(new Set(codingLessons.map((lesson) => lesson.track)));\n}\n`;

  await fs.writeFile(outputFile, header, "utf8");
  console.log(`Generated coding lesson index for ${lessons.length} files.`);
}

buildIndex().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
